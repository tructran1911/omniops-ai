import 'server-only';
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { extractJson, isMock, withRetry } from '@/lib/gemini';
import { acceptanceSchema, contractSchema, invoiceSchema } from './schemas';
import { ACCEPTANCE_PROMPT, CONTRACT_PROMPT, INVOICE_PROMPT } from './prompts';
import { sha256 } from './hash';
import type { AcceptanceData, ContractData, InvoiceData, PdfDocType } from '@/types/domain';

type DataOf<T extends PdfDocType> = T extends 'contract' ? ContractData : T extends 'acceptance' ? AcceptanceData : InvoiceData;

const CONFIG: Record<PdfDocType, { prompt: string; schema: object }> = {
  contract: { prompt: CONTRACT_PROMPT, schema: contractSchema },
  acceptance: { prompt: ACCEPTANCE_PROMPT, schema: acceptanceSchema },
  invoice: { prompt: INVOICE_PROMPT, schema: invoiceSchema },
};

export const PROMPTS_HASH = sha256(Object.values(CONFIG).map((c) => c.prompt).join('\n---\n'));

/** Ask Gemini to extract one PDF document into JSON following the schema. */
export async function extractDoc<T extends PdfDocType>(docType: T, pdf: Buffer): Promise<DataOf<T>> {
  if (isMock()) return mockExtract(docType, pdf) as Promise<DataOf<T>>;
  const { prompt, schema } = CONFIG[docType];
  const data = await withRetry(() => extractJson<DataOf<T>>(pdf, prompt, schema));
  return normalize(docType, data) as DataOf<T>;
}

export const extractContract = (pdf: Buffer) => extractDoc('contract', pdf);
export const extractAcceptance = (pdf: Buffer) => extractDoc('acceptance', pdf);
export const extractInvoice = (pdf: Buffer) => extractDoc('invoice', pdf);

/** Make sure the arrays always exist so later steps never have to check for undefined. */
function normalize(docType: PdfDocType, raw: object) {
  const data = raw as Record<string, unknown>;
  const out = { ...data, items: Array.isArray(data.items) ? data.items : [], evidence: Array.isArray(data.evidence) ? data.evidence : [] };
  if (docType === 'contract') return { ...out, riskyClauses: Array.isArray(data.riskyClauses) ? data.riskyClauses : [] };
  return out;
}

// ---------- Mock mode (GEMINI_MOCK=true), for local dry runs only ----------

type Manifest = Record<string, { docType: PdfDocType; package: string; data: unknown }>;
let manifest: Manifest | null = null;

async function loadManifest(): Promise<Manifest> {
  if (manifest) return manifest;
  const merged: Manifest = {};
  for (const dir of [path.join('public', 'samples'), 'benchmark']) {
    try {
      Object.assign(merged, JSON.parse(await readFile(path.join(process.cwd(), dir, 'manifest.json'), 'utf-8')));
    } catch {
      // the folder has no generated data yet: skip it
    }
  }
  return (manifest = merged);
}

async function mockExtract(docType: PdfDocType, pdf: Buffer) {
  const entry = (await loadManifest())[sha256(pdf)];
  if (!entry || entry.docType !== docType) {
    throw new Error('Mock mode can only read documents generated by scripts/gen_packages.py');
  }
  await new Promise((r) => setTimeout(r, 1200)); // simulate latency so the progress bar is visible
  return structuredClone(entry.data);
}
